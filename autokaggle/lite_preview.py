"""Static, escaped website for an accepted AutoKaggle Lite contract.

The caller must check project access and package freshness before rendering.
Researcher text never becomes HTML, a stylesheet, or an executable URL.
"""
from __future__ import annotations

import html
import json
import re
from urllib.parse import quote, urlsplit


def _text(value, default="Not recorded"):
    if value is None or value == "":
        value = default
    if isinstance(value, (dict, list)):
        value = json.dumps(value, indent=2, ensure_ascii=False)
    return html.escape(str(value), quote=True)


def _safe_link(value):
    if not isinstance(value, str) or any(ord(char) < 32 for char in value):
        return None
    try:
        parts = urlsplit(value)
        if parts.scheme not in {"https", "http"} or not parts.netloc or parts.username or parts.password:
            return None
        return html.escape(value, quote=True)
    except ValueError:
        return None


def _inline(value):
    # This intentionally supports only code spans and bold. HTML and Markdown
    # links stay escaped text. Source links use the separately checked renderer.
    escaped = html.escape(value, quote=True)
    escaped = re.sub(r"`([^`\n]+)`", r"<code>\1</code>", escaped)
    return re.sub(r"\*\*([^*\n]+)\*\*", r"<strong>\1</strong>", escaped)


def _readme(value):
    """Render a small safe Markdown subset without accepting embedded HTML."""
    output, paragraph, code = [], [], []
    list_kind = None
    in_code = False

    def flush_paragraph():
        if paragraph:
            output.append("<p>" + _inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()

    def close_list():
        nonlocal list_kind
        if list_kind:
            output.append(f"</{list_kind}>")
            list_kind = None

    for line in str(value or "").splitlines():
        if line.startswith("```"):
            flush_paragraph()
            close_list()
            if in_code:
                output.append("<pre><code>" + html.escape("\n".join(code), quote=True) + "</code></pre>")
                code.clear()
            in_code = not in_code
            continue
        if in_code:
            code.append(line)
            continue
        heading = re.match(r"^(#{1,6})\s+(.+)$", line)
        item = re.match(r"^\s*(?:([-*])\s+|\d+\.\s+)(.*)$", line)
        if heading:
            flush_paragraph()
            close_list()
            level = min(len(heading[1]) + 1, 4)
            output.append(f"<h{level}>" + _inline(heading[2]) + f"</h{level}>")
        elif item:
            flush_paragraph()
            kind = "ul" if item[1] else "ol"
            if list_kind != kind:
                close_list()
                list_kind = kind
                output.append(f"<{kind}>")
            output.append("<li>" + _inline(item[2]) + "</li>")
        elif not line.strip():
            flush_paragraph()
            close_list()
        else:
            close_list()
            paragraph.append(line.strip())
    flush_paragraph()
    close_list()
    if in_code:
        output.append("<pre><code>" + html.escape("\n".join(code), quote=True) + "</code></pre>")
    return "\n".join(output)


def _field(label, value, default="Not recorded"):
    return f"<div class='field'><dt>{_text(label)}</dt><dd>{_text(value, default)}</dd></div>"


