    count = contract.get("evaluation_count")
    unit = "episodes" if environment else "seeded runs"
    steps = "No step limit; time limits still apply" if "max_steps" in contract and contract["max_steps"] is None else contract.get("max_steps")
    timeout = str(contract["timeout_seconds"]) + " seconds" if contract.get("timeout_seconds") else None
    total_timeout = str(contract["total_timeout_seconds"]) + " seconds" if contract.get("total_timeout_seconds") else None
    failure = {"zero": "Retain failures with zero contribution", "fail_run": "Mark the run incomplete if an evaluation fails"}.get(contract.get("failure_policy"), contract.get("failure_policy"))
    current_results = [r for r in state.get("results", []) if r.get("version") == version]
    source_rows = []
    for source in state.get("sources", []):
        url = source.get("url", "")
        label = source.get("title") or url or "Uploaded source"
        href = _safe_link(url)
        name = f"<a href='{href}' target='_blank' rel='noopener noreferrer'>{_text(label)}</a>" if href else _text(label)
        revision = source.get("commit") or source.get("sha256")
        source_rows.append("<li><span class='source-kind'>" + _text(source.get("kind", "Source")) + "</span><strong>" + name + "</strong>" + ("<span class='digest'>Revision or SHA-256: " + _text(revision) + "</span>" if revision else "") + "</li>")
