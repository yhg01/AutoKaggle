"""Verify named accounts and shared interview activity with live OpenRouter calls.

Use a temporary store and captured local email transport. No production account
is changed and no email is sent. This does not test Gmail delivery.
"""
import argparse
import copy
import json
import os
from pathlib import Path
import secrets
import tempfile

from dotenv import dotenv_values
from fastapi.testclient import TestClient


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env-file", type=Path, default=Path(".env"))
    parser.add_argument("--report", type=Path, default=Path("autokaggle/test-results/researcher-names-live.json"))
    args = parser.parse_args()
    key = dotenv_values(args.env_file).get("OPENROUTER_API_KEY")
    if not key:
        raise SystemExit("The private OpenRouter key is unavailable.")
    admin_key = secrets.token_urlsafe(36)
    os.environ.update(OPENAI_API_KEY=key, OPENAI_BASE_URL="https://openrouter.ai/api/v1",
        AUTOKAGGLE_MODEL="openai/gpt-6.1-sol", AUTOKAGGLE_MODE="model",
        AUTOKAGGLE_PRIVATE_MODE="1", AUTOKAGGLE_ADMIN_ACCESS_CODE=admin_key,
        AUTOKAGGLE_PUBLIC_BASE_URL="https://testserver")
    from autokaggle import email_auth, notifications
    from autokaggle.app import create_app
    deliveries = []
    notifications.email_login_available = lambda: True
    notifications.send_login_code = lambda email, code: deliveries.append(code)
    email_auth.RESEND_SECONDS = 0
    names = ["ProfileOnly Sentinel One", "ProfileOnly Sentinel Two"]
    report = {"provider": "OpenRouter", "model": "openai/gpt-6.1-sol", "reasoning": "medium",
        "email_delivery": "Captured local transport; not live Gmail coverage.", "passed": False, "checks": {}}
    app = None
    try:
        with tempfile.TemporaryDirectory(prefix="autokaggle-named-researchers-") as directory:
            app = create_app(Path(directory))
            with TestClient(app, base_url="https://testserver") as owner, TestClient(app, base_url="https://testserver") as colleague, TestClient(app, base_url="https://testserver") as admin:
                def headers(client):
                    return {"Origin": "https://testserver", "X-CSRF-Token": client.get("/api/access").json()["csrf_token"]}

                def login(client, email, administrator=False):
                    response = client.post("/api/access/email/request", json={"email": email}, headers=headers(client))
                    response.raise_for_status()
                    payload = {"challenge_id": response.json()["challenge_id"], "code": deliveries[-1]}
                    if administrator:
                        payload["access_code"] = admin_key
                    response = client.post("/api/access/email/verify", json=payload, headers=headers(client))
                    response.raise_for_status()
                    return response.json()

                def name(client, value):
                    account = client.get("/api/access/profile").json()["account_id"]
                    response = client.patch("/api/access/profile", json={"name": value, "account_id": account}, headers=headers(client))
                    response.raise_for_status()
                    assert response.json()["name"] == value

                assert login(owner, "named-owner@example.org")["profile_required"]
                owner_id = app.state.access.email_auth.identity(owner.cookies[email_auth.USER_COOKIE])["owner"]
                name(owner, names[0])
                identifier = owner.post("/api/projects", json={"title": "Synthetic material survival", "storage_accepted": True}).json()["id"]
                root = "/api/projects/" + identifier
                first = "We want to predict whether a simulated material survives one specified stress test, using tabular measurements made before testing. Useful progress means balanced accuracy above 0.8 on unseen materials."
                response = owner.post(root + "/conversation/messages", json={"message": first, "request_id": "named-owner-answer"})
                response.raise_for_status()
                assert response.json()["status"] == "idle", response.json().get("error")
                assert next(m for m in response.json()["messages"] if m["content"] == first)["author"] == names[0] + " · Organizer"
                code = owner.post(root + "/handoff").json()["code"]
                login(colleague, "named-colleague@example.org")
                name(colleague, names[1])
                colleague.post("/api/handoffs/redeem", json={"code": code, "accepted": True}).raise_for_status()
                second = "The data are generated by our own versioned simulator at https://example.org/materials-generator. Each row is one material and its stable label. I can provide the exact generation settings later."
                response = colleague.post(root + "/conversation/messages", json={"message": second, "request_id": "named-colleague-answer"})
                response.raise_for_status()
                assert response.json()["status"] == "idle", response.json().get("error")
                assert next(m for m in response.json()["messages"] if m["content"] == second)["author"].startswith(names[1] + " · Collaborator ")
                assert owner.get(root + "/handoff").json()["members"][0]["name"] == names[1]
                saved = app.state.store.get(identifier, owner_id)
                traces = saved.get("_model_traces", [])
                assert traces and all(not any(value in trace["input"] for value in names) for trace in traces)
                report["checks"].update(named_owner_interview=True, named_collaborator_interview=True,
                    profile_names_excluded_from_model_context=True, shared_members_named=True)
                login(admin, "names-admin@example.org", True)
                assert colleague.patch("/api/access/researcher-profiles/" + identifier, json={"name": "Unauthorized rename"}, headers=headers(colleague)).status_code == 403
                before = copy.deepcopy(saved)
                updated = names[0] + " Updated"
                admin.patch("/api/access/researcher-profiles/" + identifier, json={"name": updated}, headers=headers(admin)).raise_for_status()
                assert app.state.store.get(identifier, owner_id) == before
                assert admin.get("/api/internal/projects", params={"q": updated}).json()["projects"][0]["id"] == identifier
                assert owner.get("/api/access/profile").json()["name"] == updated
                owner.post("/api/access/logout", json={}, headers=headers(owner)).raise_for_status()
                assert login(owner, "named-owner@example.org")["profile_required"] is False
                assert owner.get(root).status_code == 200
                assert app.state.access.email_auth.identity(owner.cookies[email_auth.USER_COOKIE])["owner"] == owner_id
                report["checks"].update(admin_name_search=True, admin_label_changes_no_scientific_records=True,
                    collaborator_cannot_rename_another_account=True, same_account_after_sign_in=True)
                report["model_calls"] = saved["_model_calls"]
                report["passed"] = True
    finally:
        if app:
            app.state.pool.shutdown(wait=True)
        args.report.parent.mkdir(parents=True, exist_ok=True)
        args.report.write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
